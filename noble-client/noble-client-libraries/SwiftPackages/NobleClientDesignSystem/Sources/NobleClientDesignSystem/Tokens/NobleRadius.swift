import Foundation

/// Corner radius tokens for the NOBLE design system.
public enum NobleRadius {
    /// 4pt — Small radius for badges and inputs.
    public static let sm: CGFloat = 4

    /// 8pt — Default radius for cards and panels.
    public static let md: CGFloat = 8

    /// 9999pt — Pill / fully rounded.
    public static let pill: CGFloat = 9999
}
