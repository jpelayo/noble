//! Self-signed TLS certificate management.
//!
//! On first startup, a 10-year self-signed certificate is generated and saved to
//! `<data_dir>/tls-cert.pem` + `<data_dir>/tls-key.pem`.  Subsequent startups
//! load the existing files so clients never see an unexpected cert change.
//!
//! The certificate covers:
//! - DNS SAN: `localhost`
//! - IP SAN:  `127.0.0.1`, `::1`
//! - Any extra SANs passed by the caller (LAN IPs, hostnames, etc.)
//!
//! When remote access is enabled and clients connect over LAN/WAN, they must
//! either accept the self-signed cert or operators can replace the files with
//! a proper CA-signed certificate in PEM format.

use std::path::Path;
use std::sync::Arc;

use openssl::pkey::PKey;
use openssl::x509::X509;
use rcgen::{Certificate, CertificateParams, SanType};
use rustls_pki_types::{CertificateDer, PrivateKeyDer, PrivatePkcs8KeyDer};
use sha2::Digest as _;

/// Certificate metadata returned by lifecycle functions.
#[derive(Debug, Clone)]
pub struct TlsCertInfo {
    /// SHA-256 fingerprint of the certificate DER bytes (hex).
    pub fingerprint: String,
    /// ISO 8601 `not_after` timestamp.
    pub expires_at: String,
    /// Unix timestamp (seconds) of `not_after`, for computing days remaining without parsing.
    pub expiry_secs: i64,
    /// Subject Alternative Names (DNS names and IP addresses).
    pub sans: Vec<String>,
    /// True when generated by the node (self-signed); false for CA-uploaded certs.
    #[allow(dead_code)]
    pub auto_generated: bool,
}

/// Load an existing TLS certificate from `data_dir`, or generate a new one.
///
/// `extra_sans` is a list of additional IP addresses or DNS names to include in
/// the Subject Alternative Names of a newly generated certificate.  When loading
/// an existing cert the list is advisory — a warning is emitted if any requested
/// SANs are missing from the cert.
///
/// Startup expiry checks:
/// - Expired cert → returns `Err` (fail-closed)
/// - < 30 days remaining → prominent `tracing::warn!`
/// - < 90 days remaining → `tracing::info!`
///
/// Returns an `Arc<rustls::ServerConfig>` ready to be used with `TlsAcceptor`.
pub fn load_or_generate(
    data_dir: &Path,
    extra_sans: &[String],
) -> Result<Arc<rustls::ServerConfig>, Box<dyn std::error::Error + Send + Sync>> {
    let cert_path = data_dir.join("tls-cert.pem");
    let key_path = data_dir.join("tls-key.pem");

    let (cert_ders, key_der) = if cert_path.exists() && key_path.exists() {
        let (all_certs, key) = load_from_files(&cert_path, &key_path)?;
        // Run expiry check and SAN diff against the loaded cert.
        check_existing_cert(&cert_path, &key_path, extra_sans)?;
        (all_certs, key)
    } else {
        let (cert, key) = generate_and_save(&cert_path, &key_path, extra_sans)?;
        (vec![cert], key)
    };

    let config = rustls::ServerConfig::builder()
        .with_no_client_auth()
        .with_single_cert(cert_ders, key_der)?;

    Ok(Arc::new(config))
}

/// Compute and return the SHA-256 fingerprint of the TLS certificate stored in `data_dir`.
///
/// Returns `None` if the certificate file does not exist or cannot be parsed.
pub fn certificate_fingerprint(data_dir: &Path) -> Option<String> {
    let cert_path = data_dir.join("tls-cert.pem");
    let cert_pem = std::fs::read_to_string(&cert_path).ok()?;
    let cert_der = pem::parse_many(cert_pem).ok()?.into_iter().next()?.into_contents();
    let digest = sha2::Sha256::digest(&cert_der);
    Some(hex::encode(digest))
}

/// Return the ISO 8601 `not_after` expiry of the certificate in `data_dir`.
///
/// Returns `None` if the cert file is absent or cannot be parsed.
pub fn certificate_expiry(data_dir: &Path) -> Option<String> {
    let cert_pem = std::fs::read(data_dir.join("tls-cert.pem")).ok()?;
    let cert = X509::from_pem(&cert_pem).ok()?;
    asn1_time_to_iso(cert.not_after())
}

/// Return the Unix timestamp (seconds) of `not_after` for the certificate in `data_dir`.
///
/// Useful for computing days-remaining without needing to parse an ISO string.
/// Returns `None` if the cert file is absent or cannot be parsed.
pub fn certificate_expiry_secs(data_dir: &Path) -> Option<i64> {
    let cert_pem = std::fs::read(data_dir.join("tls-cert.pem")).ok()?;
    let cert = X509::from_pem(&cert_pem).ok()?;
    asn1_time_to_secs(cert.not_after())
}

/// Return the Subject Alternative Names from the certificate in `data_dir`.
///
/// Returns an empty vec if the cert file is absent or cannot be parsed.
pub fn certificate_sans(data_dir: &Path) -> Vec<String> {
    let cert_pem = match std::fs::read(data_dir.join("tls-cert.pem")) {
        Ok(p) => p,
        Err(_) => return vec![],
    };
    let cert = match X509::from_pem(&cert_pem) {
        Ok(c) => c,
        Err(_) => return vec![],
    };
    extract_sans(&cert)
}

/// Return combined certificate metadata for the cert in `data_dir`.
///
/// Returns `None` if the cert file is absent or cannot be parsed.
#[allow(dead_code)]
pub fn certificate_details(data_dir: &Path) -> Option<TlsCertInfo> {
    let cert_pem = std::fs::read(data_dir.join("tls-cert.pem")).ok()?;
    let cert = X509::from_pem(&cert_pem).ok()?;
    // Fingerprint from the first (leaf) PEM block.
    let cert_der = pem::parse_many(&cert_pem).ok()?.into_iter().next()?.into_contents();
    let fingerprint = hex::encode(sha2::Sha256::digest(&cert_der));
    let expiry_secs = asn1_time_to_secs(cert.not_after())?;
    let expires_at = asn1_time_to_iso(cert.not_after())?;
    let sans = extract_sans(&cert);
    Some(TlsCertInfo { fingerprint, expires_at, expiry_secs, sans, auto_generated: true })
}

/// Delete the existing cert/key files in `data_dir` and generate a fresh self-signed
/// certificate with the given `extra_sans`.
///
/// Returns `TlsCertInfo` for the new certificate.
pub fn regenerate(
    data_dir: &Path,
    extra_sans: &[String],
) -> Result<TlsCertInfo, Box<dyn std::error::Error + Send + Sync>> {
    let cert_path = data_dir.join("tls-cert.pem");
    let key_path = data_dir.join("tls-key.pem");

    if cert_path.exists() {
        std::fs::remove_file(&cert_path)?;
    }
    if key_path.exists() {
        std::fs::remove_file(&key_path)?;
    }

    let (cert_der, _) = generate_and_save(&cert_path, &key_path, extra_sans)?;

    // Parse the written cert for metadata.
    let cert_pem = std::fs::read(&cert_path)?;
    let cert = X509::from_pem(&cert_pem)?;
    let fingerprint = hex::encode(sha2::Sha256::digest(cert_der.as_ref()));
    let expiry_secs = asn1_time_to_secs(cert.not_after())
        .ok_or("failed to parse cert not_after")?;
    let expires_at = asn1_time_to_iso(cert.not_after())
        .ok_or("failed to format cert not_after")?;
    let sans = extract_sans(&cert);

    Ok(TlsCertInfo { fingerprint, expires_at, expiry_secs, sans, auto_generated: true })
}

/// Validate an externally supplied certificate and private key, then write them to
/// `<data_dir>/tls-cert.pem` and `<data_dir>/tls-key.pem` atomically.
///
/// `cert_pem` — PEM-encoded leaf certificate (required).
/// `key_pem`  — PEM-encoded private key (required).
/// `chain_pem` — PEM-encoded intermediate chain (optional). When supplied the
///               full-chain PEM (`chain_pem + "\n" + cert_pem`) is written so that
///               TLS clients can verify the complete certificate chain.
///
/// Validation performed before writing:
/// - `cert_pem` parses as valid X.509
/// - `key_pem` parses as valid private key
/// - The private key's public key matches the certificate's public key
///
/// Returns `TlsCertInfo` for the uploaded certificate on success.
pub fn validate_and_write(
    data_dir: &Path,
    cert_pem: &str,
    key_pem: &str,
    chain_pem: Option<&str>,
) -> Result<TlsCertInfo, Box<dyn std::error::Error + Send + Sync>> {
    // Parse and validate cert + key.
    let cert = X509::from_pem(cert_pem.as_bytes())
        .map_err(|e| format!("invalid certificate PEM: {e}"))?;
    let pkey = PKey::private_key_from_pem(key_pem.as_bytes())
        .map_err(|e| format!("invalid private key PEM: {e}"))?;

    // Validate: public key in cert must match public key derived from private key.
    let cert_pub_der = cert
        .public_key()
        .map_err(|e| format!("cannot read cert public key: {e}"))?
        .public_key_to_der()
        .map_err(|e| format!("cannot encode cert public key: {e}"))?;
    let key_pub_der = pkey
        .public_key_to_der()
        .map_err(|e| format!("cannot encode private key public component: {e}"))?;
    if cert_pub_der != key_pub_der {
        return Err("private key does not match certificate public key".into());
    }

    // Build the final cert PEM: leaf first, chain (if any) appended after.
    // Standard TLS order: leaf cert must be the first PEM block so that
    // load_from_files(), certificate_fingerprint(), and certificate_details()
    // can use pem::parse_many()[0] to get the leaf for fingerprinting.
    let final_cert_pem = if let Some(chain) = chain_pem {
        format!("{}\n{}", cert_pem.trim_end(), chain)
    } else {
        cert_pem.to_string()
    };

    // Compute fingerprint from the leaf cert DER.
    let cert_der_bytes = pem::parse(cert_pem.as_bytes())
        .map_err(|e| format!("cannot re-parse cert PEM for fingerprint: {e}"))?
        .into_contents();
    let fingerprint = hex::encode(sha2::Sha256::digest(&cert_der_bytes));
    let expiry_secs = asn1_time_to_secs(cert.not_after())
        .ok_or("failed to parse cert not_after")?;
    let expires_at = asn1_time_to_iso(cert.not_after())
        .ok_or("failed to format cert not_after")?;
    let sans = extract_sans(&cert);

    // Atomic write: write .tmp → rename.
    let cert_path = data_dir.join("tls-cert.pem");
    let key_path = data_dir.join("tls-key.pem");
    if let Some(parent) = cert_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let cert_tmp = cert_path.with_extension("tmp");
    let key_tmp = key_path.with_extension("tmp");

    std::fs::write(&cert_tmp, final_cert_pem.as_bytes())?;
    std::fs::write(&key_tmp, key_pem.as_bytes())?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&key_tmp, std::fs::Permissions::from_mode(0o600))?;
    }

    std::fs::rename(&cert_tmp, &cert_path)?;
    std::fs::rename(&key_tmp, &key_path)?;

    tracing::info!(
        task = "tls_cert",
        "Uploaded TLS certificate — SHA-256: {fingerprint}"
    );

    Ok(TlsCertInfo { fingerprint, expires_at, expiry_secs, sans, auto_generated: false })
}

