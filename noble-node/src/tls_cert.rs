/// Check an existing certificate for expiry and SAN mismatches.
/// - Expired → returns `Err` (fail-closed)
/// - < 30 days remaining → `tracing::warn!` banner
/// - < 90 days remaining → `tracing::info!`
/// - Any `extra_sans` not present in cert → `tracing::warn!`
fn check_existing_cert(
    cert_path: &Path,
    key_path: &Path,
    extra_sans: &[String],
) -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
    let cert_pem = match std::fs::read(cert_path) {
        Ok(p) => p,
        Err(_) => return Ok(()), // can't read — let load_from_files surface the error
    };
    let cert = match X509::from_pem(&cert_pem) {
        Ok(c) => c,
        Err(_) => return Ok(()), // can't parse — let rustls surface the error
    };

    // --- Expiry check ---
    let now_secs = time::OffsetDateTime::now_utc().unix_timestamp();
    if let Ok(epoch) = openssl::asn1::Asn1Time::from_unix(0) {
        if let Ok(diff) = epoch.diff(cert.not_after()) {
            let expiry_secs = (diff.days as i64) * 86400 + diff.secs as i64;
            let days_remaining = (expiry_secs - now_secs) / 86400;

            if days_remaining < 0 {
                let expiry_str = asn1_time_to_iso(cert.not_after()).unwrap_or_default();
                return Err(format!(
                    "TLS certificate expired on {expiry_str}. \
                     Delete {cert_path:?} and {key_path:?} and restart the node to regenerate, \
                     or call noble_regenerateTlsCert via the RPC.",
                )
                .into());
            } else if days_remaining < 30 {
                let sep = "═".repeat(60);
                tracing::warn!(task = "tls_cert", "{sep}");
                tracing::warn!(
                    task = "tls_cert",
                    "  ⚠  TLS CERTIFICATE EXPIRES IN {days_remaining} DAYS  ⚠"
                );
                tracing::warn!(
                    task = "tls_cert",
                    "  Call noble_regenerateTlsCert or replace {cert_path:?} and restart."
                );
                tracing::warn!(task = "tls_cert", "{sep}");
            } else if days_remaining < 90 {
                tracing::info!(
                    task = "tls_cert",
                    "TLS certificate expires in {days_remaining} days — consider renewing."
                );
            }
        }
    }

    // --- SAN diff check ---
    if !extra_sans.is_empty() {
        let actual_sans = extract_sans(&cert);
        let missing: Vec<&str> = extra_sans
            .iter()
            .filter(|req| {
                let req_norm = req
                    .parse::<std::net::IpAddr>()
                    .map(|ip| ip.to_string())
                    .unwrap_or_else(|_| req.to_lowercase());
                !actual_sans.iter().any(|actual| {
                    let actual_norm = actual
                        .parse::<std::net::IpAddr>()
                        .map(|ip| ip.to_string())
                        .unwrap_or_else(|_| actual.to_lowercase());
                    req_norm == actual_norm
                })
            })
            .map(|s| s.as_str())
            .collect();

        if !missing.is_empty() {
            tracing::warn!(
                task = "tls_cert",
                "Existing TLS certificate is missing requested SANs: {missing:?}. \
                 Delete {cert_path:?} and {key_path:?} and restart, \
                 or call noble_regenerateTlsCert, to include the new SANs."
            );
        }
    }

    Ok(())
}

/// Extract SANs from an X.509 certificate as human-readable strings.
fn extract_sans(cert: &X509) -> Vec<String> {
    let mut result = Vec::new();
    if let Some(san_stack) = cert.subject_alt_names() {
        for san in san_stack {
            if let Some(dns) = san.dnsname() {
                result.push(dns.to_string());
            } else if let Some(ip_bytes) = san.ipaddress() {
                let ip_str = if ip_bytes.len() == 4 {
                    let arr: [u8; 4] = match ip_bytes.try_into() {
                        Ok(a) => a,
                        Err(_) => continue,
                    };
                    std::net::IpAddr::V4(std::net::Ipv4Addr::from(arr)).to_string()
                } else if ip_bytes.len() == 16 {
                    let arr: [u8; 16] = match ip_bytes.try_into() {
                        Ok(a) => a,
                        Err(_) => continue,
                    };
                    std::net::IpAddr::V6(std::net::Ipv6Addr::from(arr)).to_string()
                } else {
                    continue;
                };
                result.push(ip_str);
            }
        }
    }
    result
}

/// Convert an `Asn1TimeRef` to Unix seconds since epoch.
fn asn1_time_to_secs(asn1: &openssl::asn1::Asn1TimeRef) -> Option<i64> {
    let epoch = openssl::asn1::Asn1Time::from_unix(0).ok()?;
    let diff = epoch.diff(asn1).ok()?;
    Some((diff.days as i64) * 86400 + diff.secs as i64)
}

/// Convert an `Asn1TimeRef` to an ISO 8601 / RFC 3339 string.
///
/// Uses diff from Unix epoch to compute the timestamp without external date libraries.
fn asn1_time_to_iso(asn1: &openssl::asn1::Asn1TimeRef) -> Option<String> {
    let total_secs = asn1_time_to_secs(asn1)?;
    let dt = time::OffsetDateTime::from_unix_timestamp(total_secs).ok()?;
    dt.format(&time::format_description::well_known::Rfc3339).ok()
}

fn generate_and_save(
    cert_path: &Path,
    key_path: &Path,
    extra_sans: &[String],
) -> Result<(CertificateDer<'static>, PrivateKeyDer<'static>), Box<dyn std::error::Error + Send + Sync>>
{
    let mut params = CertificateParams::default();
    let mut sans = vec![
        SanType::DnsName("localhost".to_string()),
        SanType::IpAddress(std::net::IpAddr::V4(std::net::Ipv4Addr::new(127, 0, 0, 1))),
        SanType::IpAddress(std::net::IpAddr::V6(std::net::Ipv6Addr::LOCALHOST)),
    ];

    // Parse and add extra SANs (IP addresses or DNS names).
    for san_str in extra_sans {
        if let Ok(ip) = san_str.parse::<std::net::IpAddr>() {
            // Skip loopback addresses already in the base set.
            if !ip.is_loopback() {
                sans.push(SanType::IpAddress(ip));
            }
        } else if !san_str.is_empty() {
            // Treat as a DNS name.
            if san_str != "localhost" {
                sans.push(SanType::DnsName(san_str.clone()));
            }
        }
    }

    params.subject_alt_names = sans;

    // 10-year validity
    params.not_before = time::OffsetDateTime::now_utc();
    params.not_after = time::OffsetDateTime::now_utc() + time::Duration::days(3650);

    let cert = Certificate::from_params(params)?;
    let cert_pem = cert.serialize_pem()?;
    let key_pem = cert.serialize_private_key_pem();
    let cert_der_bytes = cert.serialize_der()?;
    let key_der_bytes = cert.serialize_private_key_der();

    // Ensure data_dir exists
    if let Some(parent) = cert_path.parent() {
        std::fs::create_dir_all(parent)?;
    }

    std::fs::write(cert_path, &cert_pem)?;
    std::fs::write(key_path, &key_pem)?;

    // Restrict key file permissions on Unix
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(key_path, std::fs::Permissions::from_mode(0o600))?;
    }

    let fingerprint = sha2::Sha256::digest(&cert_der_bytes);
    tracing::info!(
        task = "tls_cert",
        "Generated self-signed TLS certificate — SHA-256: {}",
        hex::encode(fingerprint)
    );

    Ok((
        CertificateDer::from(cert_der_bytes),
        PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(key_der_bytes)),
    ))
}

fn load_from_files(
    cert_path: &Path,
    key_path: &Path,
) -> Result<(Vec<CertificateDer<'static>>, PrivateKeyDer<'static>), Box<dyn std::error::Error + Send + Sync>>
{
    let cert_pem = std::fs::read_to_string(cert_path)?;
    let key_pem = std::fs::read_to_string(key_path)?;

    // Parse all PEM blocks (leaf + any intermediate chain certs).
    // After the validate_and_write ordering fix, the leaf cert is always first.
    let all_pem_blocks = pem::parse_many(&cert_pem)?;
    if all_pem_blocks.is_empty() {
        return Err("TLS certificate PEM contains no blocks".into());
    }

    let key_der = pem::parse(key_pem)?.into_contents();

    // Log fingerprint of the leaf cert (first block).
    let leaf_der = all_pem_blocks[0].contents().to_vec();
    let fingerprint = sha2::Sha256::digest(&leaf_der);
    tracing::info!(
        task = "tls_cert",
        "Loaded TLS certificate from {:?} — SHA-256: {} ({} PEM block(s))",
        cert_path,
        hex::encode(fingerprint),
        all_pem_blocks.len()
    );

    let all_cert_ders: Vec<CertificateDer<'static>> = all_pem_blocks
        .into_iter()
        .map(|b| CertificateDer::from(b.into_contents()))
        .collect();

    Ok((
        all_cert_ders,
        PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(key_der)),
    ))
}

